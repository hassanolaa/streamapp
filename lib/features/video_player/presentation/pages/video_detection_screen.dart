  Future<void> _openMuxed() async {
    _stopAudioSync();
    await _audioPlayer.stop();

    await _videoPlayer.open(Media(_videoStreams[_videoIndex].url));
    await _videoPlayer.play();
    
    // IMPORTANT: Also open in detection player for streaming mode
    await _detectionPlayer.open(Media(_videoStreams[_videoIndex].url));
    await _detectionPlayer.setVolume(0.0); // Keep it muted
    
    if (_isDetectionEnabled) {
      final aheadPos = _videoPlayer.state.position + 
          Duration(seconds: DETECTION_AHEAD_SECONDS);
      await _detectionPlayer.seek(aheadPos);
      await _detectionPlayer.play();
    } else {
      await _detectionPlayer.pause(); // Keep it paused if detection is off
    }
  }

  Future<void> _openAdaptive() async {
    _stopAudioSync();

    final video = _videoOnlyStreams[_videoIndex];
    final audio = _audioStreams[_audioIndex];

    await _videoPlayer.open(Media(video.url), play: false);
    await _audioPlayer.open(Media(audio.url), play: false);

    await _videoPlayer.seek(Duration.zero);
    await _audioPlayer.seek(Duration.zero);

    await _videoPlayer.play();
    await _audioPlayer.play();

    _startAudioSync();

    // IMPORTANT: Detection player must use the VIDEO-ONLY stream
    await _detectionPlayer.open(Media(video.url));
    await _detectionPlayer.setVolume(0.0);
    
    if (_isDetectionEnabled) {
      final aheadPos = Duration(seconds: DETECTION_AHEAD_SECONDS);
      await _detectionPlayer.seek(aheadPos);
      await _detectionPlayer.play();
    } else {
      await _detectionPlayer.pause();
    }
  }

  Future<void> _openAudioOnly() async {
    _stopAudioSync();
    await _videoPlayer.stop();
    await _detectionPlayer.stop(); // Stop detection in audio-only mode

    await _audioPlayer.open(Media(_audioStreams[_audioIndex].url));
    await _audioPlayer.play();
  }

  void _reload() {
    switch (_mode) {
      case PlaybackMode.muxed:
        _openMuxed();
        break;
      case PlaybackMode.adaptive:
        _openAdaptive();
        break;
      case PlaybackMode.audioOnly:
        _openAudioOnly();
        break;
    }
  }

  void _startAudioSync() {
    _audioSyncTimer?.cancel();

    _audioSyncTimer = Timer.periodic(
      const Duration(milliseconds: SYNC_INTERVAL_MS),
      (timer) {
        if (!mounted || _mode != PlaybackMode.adaptive) {
          timer.cancel();
          return;
        }

        final videoPos = _videoPlayer.state.position;
        final audioPos = _audioPlayer.state.position;
        final diffMs = (audioPos - videoPos).inMilliseconds;

        if (diffMs.abs() > 300) {
          _audioPlayer.seek(videoPos);
          _audioPlayer.setRate(1.0);
        } else if (diffMs.abs() > 80) {
          final correction = diffMs * -0.001;
          final rate = (1.0 + correction).clamp(0.95, 1.05);
          _audioPlayer.setRate(rate);
        } else {
          _audioPlayer.setRate(_currentSpeed);
        }
      },
    );
  }

  void _stopAudioSync() {
    _audioSyncTimer?.cancel();
    _audioSyncTimer = null;
    _audioPlayer.setRate(_currentSpeed);
  }

  /// =====================
  /// SUBTITLE HANDLING
