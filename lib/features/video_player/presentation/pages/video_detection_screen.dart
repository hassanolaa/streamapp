  void _startDetection() async {
    if (_mode == PlaybackMode.audioOnly) {
      _showSnackbar('Detection not available in audio-only mode');
      return;
    }

    setState(() {
      _isDetectionEnabled = true;
      _frameCount = 0;
      _fpsHistory.clear();
      _detectionCache.clear();
      _lastLookupKey = -1;
      _syncDriftMs = 0;
      _statusMessage = 'Detection active';
    });

    final mainPosition = _videoPlayer.state.position;
    final videoDuration = _videoPlayer.state.duration ?? Duration.zero;
    final aheadMs = (mainPosition.inMilliseconds + DETECTION_AHEAD_SECONDS * 1000)
        .clamp(0, videoDuration.inMilliseconds);
    final aheadPosition = Duration(milliseconds: aheadMs);

    // Make sure detection player is playing
    await _detectionPlayer.play();
    await _detectionPlayer.seek(aheadPosition);
    await Future.delayed(const Duration(milliseconds: 300));

    _captureTimer = Timer.periodic(
      const Duration(milliseconds: CAPTURE_INTERVAL_MS),
      (timer) {
        if (!mounted || !_isDetectionEnabled) {
          timer.cancel();
          return;
        }

        if (!_isProcessing && _detectionPlayer.state.playing) {
          _captureAndDetect();
        }
      },
    );

    _syncTimer = Timer.periodic(
      const Duration(milliseconds: SYNC_INTERVAL_MS),
      (timer) {
        if (!mounted || !_isDetectionEnabled) {
          timer.cancel();
          return;
        }

        _syncDetections();
      },
    );

    _syncCheckTimer = Timer.periodic(
      const Duration(milliseconds: SYNC_CHECK_INTERVAL_MS),
      (timer) {
        if (!mounted || !_isDetectionEnabled) {
          timer.cancel();
          return;
        }

        _checkAndCorrectSync();
      },
    );
  }

  void _stopDetection() {
    _captureTimer?.cancel();
    _syncTimer?.cancel();
    _syncCheckTimer?.cancel();
    _detectionPlayer.pause();

    setState(() {
      _isDetectionEnabled = false;
      _currentDetections = [];
      _detectionCache.clear();
      _objectCount = 0;
      _fps = 0.0;
      _frameCount = 0;
      _fpsHistory.clear();
      _lastLookupKey = -1;
      _syncDriftMs = 0;
      _statusMessage = 'Detection stopped';
    });
  }

  void _checkAndCorrectSync() async {
    if (!_isDetectionEnabled || !mounted) return;

    final mainPos = _videoPlayer.state.position.inMilliseconds;
    final detectionPos = _detectionPlayer.state.position.inMilliseconds;
    final expectedDetectionPos = mainPos + (DETECTION_AHEAD_SECONDS * 1000);
    final actualDrift = (detectionPos - expectedDetectionPos).abs();

    if (mounted) {
      setState(() {
        _syncDriftMs = actualDrift;
      });
    }

    if (actualDrift > MAX_DRIFT_MS) {
      final videoDuration = _videoPlayer.state.duration ?? Duration.zero;
      final correctedPos = Duration(
          milliseconds: (mainPos + DETECTION_AHEAD_SECONDS * 1000)
              .clamp(0, videoDuration.inMilliseconds));
      await _detectionPlayer.seek(correctedPos);
    }
  }

  Future<void> _captureAndDetect() async {
    if (_isProcessing || !mounted) return;

    _isProcessing = true;

    try {
      final startTime = DateTime.now();
      final detectionPosition = _detectionPlayer.state.position;
      final timestampMs = detectionPosition.inMilliseconds;
      final timestampKey = (timestampMs / 25).round();

      if (_detectionCache.containsKey(timestampKey)) {
        _isProcessing = false;
        return;
      }

      final frameBytes = await _detectionPlayer.screenshot(format: 'image/jpeg');

      if (frameBytes == null || !mounted) {
        _isProcessing = false;
        return;
      }

      final detections = await _detector.detectObjects(
        frameBytes,
        confidenceThreshold: 0.38,
      );

      if (!mounted) {
        _isProcessing = false;
        return;
      }

      _detectionCache[timestampKey] = detections;

      final mainPosition = _videoPlayer.state.position;
      final mainKey = (mainPosition.inMilliseconds / 25).round();

      if (_detectionCache.length > CACHE_CLEANUP_THRESHOLD) {
        _detectionCache.removeWhere((key, value) => key < mainKey - 80);
      }

      final duration = DateTime.now().difference(startTime).inMilliseconds;
      final fps = duration > 0 ? 1000.0 / duration : 0.0;

      _fpsHistory.add(fps);
      if (_fpsHistory.length > 30) _fpsHistory.removeAt(0);

      _frameCount++;

      final now = DateTime.now();
      if (_lastFpsUpdate == null ||
          now.difference(_lastFpsUpdate!).inMilliseconds > 500) {
        if (mounted && _fpsHistory.isNotEmpty) {
          final avgFps = _fpsHistory.reduce((a, b) => a + b) / _fpsHistory.length;
          _fps = avgFps;
        }

        _lastFpsUpdate = now;
      }
    } catch (e) {
      print('[Detection] Error: $e');
    } finally {
      _isProcessing = false;
    }
  }

  void _syncDetections() {
    if (!mounted || !_isDetectionEnabled) return;

    final mainPosition = _videoPlayer.state.position;
    final mainMs = mainPosition.inMilliseconds;
    final timestampKey = (mainMs / 25).round();

    if (timestampKey == _lastLookupKey) return;

    _lastLookupKey = timestampKey;

    List<DetectionResult>? detections;

    if (_detectionCache.containsKey(timestampKey)) {
      detections = _detectionCache[timestampKey]!;
    } else {
      for (int offset = -8; offset <= 8; offset++) {
        final nearbyKey = timestampKey + offset;
        if (_detectionCache.containsKey(nearbyKey)) {
          detections = _detectionCache[nearbyKey]!;
          break;
        }
      }
    }

    if (detections != null) {
      if (_currentDetections.length != detections.length ||
          (_currentDetections.isEmpty && detections.isNotEmpty)) {
        setState(() {
          _currentDetections = detections!;
          _objectCount = detections.length;
        });
      }
    }
  }

