class VideoStream {
  final String url;
  final String resolution;
  final int bitrate;

  VideoStream.fromJson(Map<String, dynamic> json)
      : url = json['content'],
        resolution = json['resolution'] ?? '',
        bitrate = json['bitrate'] ?? 0;
}

class AudioStream {
  final String url;
  final int bitrate;
  final String? language;

  AudioStream.fromJson(Map<String, dynamic> json)
      : url = json['content'],
        bitrate = json['bitrate'] ?? 0,
        language = json['language'];
}

class SubtitleTrack {
  final String url;
  final String locale;
  final bool autoGenerated;
  final SubtitleType format;

  SubtitleTrack({
    required this.url,
    required this.locale,
    required this.autoGenerated,
    required this.format,
  });

  factory SubtitleTrack.fromJson(Map<String, dynamic> json) {
    final url = json['content'] ?? '';
    SubtitleType format = SubtitleType.vtt;

    if (url.contains('fmt=vtt') || url.endsWith('.vtt')) {
      format = SubtitleType.vtt;
    } else if (url.contains('fmt=ttml') ||
        url.endsWith('.ttml') ||
        url.endsWith('.xml')) {
      format = SubtitleType.ttml;
    } else if (url.endsWith('.srt')) {
      format = SubtitleType.srt;
    }

    return SubtitleTrack(
      url: url,
      locale: json['locale'] ?? 'unknown',
      autoGenerated: json['autoGenerated'] ?? false,
      format: format,
    );
  }

  String get label {
    String formatName = format.toString().split('.').last.toUpperCase();
    return '${locale.toUpperCase()}${autoGenerated ? ' (Auto)' : ''} [$formatName]';
  }
}

class SubtitleConfig {
  final double fontSize;
  final Color textColor;
  final Color backgroundColor;
  final SubtitlePosition position;
  final FontWeight fontWeight;
  final double backgroundOpacity;
  final EdgeInsets padding;
  final bool hasShadow;

  const SubtitleConfig({
    this.fontSize = 18.0,
    this.textColor = Colors.white,
    this.backgroundColor = Colors.black,
    this.position = SubtitlePosition.bottom,
    this.fontWeight = FontWeight.w600,
    this.backgroundOpacity = 0.75,
    this.padding = const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
    this.hasShadow = true,
  });

  SubtitleConfig copyWith({
    double? fontSize,
    Color? textColor,
    Color? backgroundColor,
    SubtitlePosition? position,
    FontWeight? fontWeight,
    double? backgroundOpacity,
    EdgeInsets? padding,
    bool? hasShadow,
  }) {
    return SubtitleConfig(
      fontSize: fontSize ?? this.fontSize,
      textColor: textColor ?? this.textColor,
      backgroundColor: backgroundColor ?? this.backgroundColor,
      position: position ?? this.position,
      fontWeight: fontWeight ?? this.fontWeight,
      backgroundOpacity: backgroundOpacity ?? this.backgroundOpacity,
      padding: padding ?? this.padding,
      hasShadow: hasShadow ?? this.hasShadow,
    );
  }
}

