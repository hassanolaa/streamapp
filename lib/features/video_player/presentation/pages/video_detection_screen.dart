  Future<void> _loadSubtitle(String url, SubtitleType format) async {
    setState(() => _isLoadingSubtitle = true);

    try {
      if (url.isEmpty) {
        throw Exception('Empty subtitle URL');
      }

      final response = await http.get(
        Uri.parse(url),
        headers: {
          'User-Agent':
              'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
        },
      ).timeout(const Duration(seconds: 10));

      if (response.statusCode != 200) {
        throw Exception('Failed to load subtitle: ${response.statusCode}');
      }

      final body = utf8.decode(response.bodyBytes);
      await _parseSubtitle(body, format);
      _currentSubtitleFormat = format;

      _startSubtitleSync();

      if (mounted) {
        setState(() => _isLoadingSubtitle = false);
      }
    } catch (e) {
      debugPrint('Failed to load subtitle: $e');
      _subtitleController = null;
      _currentSubtitleFormat = null;

      if (mounted) {
        setState(() {
          _currentSubtitle = '';
          _isLoadingSubtitle = false;
        });

        _showSnackbar('Failed to load subtitles: ${e.toString()}');
      }
    }
  }

  Future<void> _parseSubtitle(String content, SubtitleType format) async {
    try {
      String cleanedContent = content;
      if (format == SubtitleType.vtt) {
        cleanedContent = content
            .replaceAll(RegExp(r'<[\d:.,\s-]+>'), '')
            .replaceAll(RegExp(r'STYLE\s*\n.*?(?=\n\n|\Z)', dotAll: true), '');
      }

      final provider = SubtitleProvider.fromString(
        data: cleanedContent,
        type: format,
      );

      _subtitleController = SubtitleController(provider: provider);
      await _subtitleController!.initial();
    } catch (e) {
      debugPrint('Subtitle parsing error: $e');
      rethrow;
    }
  }

  void _startSubtitleSync() {
    _subtitleSyncSub?.cancel();

    final player = _timelinePlayer;

    _subtitleSyncSub = player.stream.position.listen((position) {
      if (_subtitleController == null) return;

      final subtitle = _subtitleController!.durationSearch(position);
      String newSubtitle = subtitle?.data ?? '';

      if (newSubtitle.isNotEmpty && _currentSubtitleFormat == SubtitleType.ttml) {
        newSubtitle = newSubtitle.parseHtmlString();
      }

      if (newSubtitle != _currentSubtitle) {
        setState(() => _currentSubtitle = newSubtitle);
      }
    });
  }

  void _stopSubtitleSync() {
    _subtitleSyncSub?.cancel();
    _subtitleSyncSub = null;
    _currentSubtitleFormat = null;
    setState(() => _currentSubtitle = '');
  }

  /// =====================
  /// UI CONTROL & KEYBOARD
  /// =====================

  void _showControlsTemporarily() {
    setState(() {
      _showControls = true;
    });
    _startHideTimer();
  }

  void _startHideTimer() {
    _hideControlsTimer?.cancel();
    _hideControlsTimer = Timer(CONTROLS_HIDE_DURATION, () {
      if (mounted &&
          _videoPlayer.state.playing &&
          !_isTimelineMode &&
          !_showVolumePopup &&
          !_showSpeedPopup &&
          !_showSettingsPopup) {
        setState(() {
          _showControls = false;
          _focusedControl = null;
        });
      }
    });
  }

  void _handleKeyPress(RawKeyEvent event) {
    if (event is RawKeyDownEvent) {
      _showControlsTemporarily();
      if (event.logicalKey == LogicalKeyboardKey.arrowUp) {
        _handleUpKey();
      } else if (event.logicalKey == LogicalKeyboardKey.arrowDown) {
        _handleDownKey();
      } else if (event.logicalKey == LogicalKeyboardKey.arrowLeft) {
        _handleLeftKey();
      } else if (event.logicalKey == LogicalKeyboardKey.arrowRight) {
        _handleRightKey();
      } else if (event.logicalKey == LogicalKeyboardKey.enter ||
          event.logicalKey == LogicalKeyboardKey.select) {
        _handleEnterKey();
      } else if (event.logicalKey == LogicalKeyboardKey.escape ||
          event.logicalKey == LogicalKeyboardKey.goBack) {
        _handleBackKey();
      }
    }
  }

  void _handleUpKey() {
    if (_showVolumePopup) {
      _adjustVolume(5);
    } else if (_showSpeedPopup) {
      _adjustSpeed(0.25);
    } else {
      setState(() {
        if (_isTimelineMode) {
          _isTimelineMode = false;
          _focusedControl = null;
        } else if (_focusedControl == null) {
          _isTimelineMode = true;
        } else {
          _isTimelineMode = true;
          _focusedControl = null;
        }
      });
    }
  }

  void _handleDownKey() {
    if (_showVolumePopup) {
      _adjustVolume(-5);
    } else if (_showSpeedPopup) {
      _adjustSpeed(-0.25);
    } else {
      setState(() {
        if (_isTimelineMode) {
          _isTimelineMode = false;
          _focusedControl = ControlButton.playPause;
        } else if (_focusedControl == null) {
          _focusedControl = ControlButton.playPause;
        }
      });
    }
  }

  void _handleLeftKey() {
    if (_showVolumePopup) {
      _adjustVolume(-5);
    } else if (_showSpeedPopup) {
      _adjustSpeed(-0.25);
    } else if (_isTimelineMode) {
      _seekBackward();
    } else {
      setState(() {
        if (_focusedControl == null) {
          _focusedControl = ControlButton.fullscreen;
        } else {
          final leftControls = [
            ControlButton.playPause,
            ControlButton.rewind,
            ControlButton.forward
          ];
          final rightControls = [
            ControlButton.detection,
            ControlButton.subtitle,
            ControlButton.volume,
            ControlButton.speed,
            ControlButton.settings,
            ControlButton.fullscreen
          ];

          if (leftControls.contains(_focusedControl)) {
            final currentIndex = leftControls.indexOf(_focusedControl!);
            if (currentIndex > 0) {
              _focusedControl = leftControls[currentIndex - 1];
            }
          } else if (rightControls.contains(_focusedControl)) {
            final currentIndex = rightControls.indexOf(_focusedControl!);
            if (currentIndex > 0) {
              _focusedControl = rightControls[currentIndex - 1];
            } else {
              _focusedControl = leftControls.last;
            }
          }
        }
      });
    }
  }

  void _handleRightKey() {
    if (_showVolumePopup) {
      _adjustVolume(5);
    } else if (_showSpeedPopup) {
      _adjustSpeed(0.25);
    } else if (_isTimelineMode) {
      _seekForward();
    } else {
      setState(() {
        if (_focusedControl == null) {
          _focusedControl = ControlButton.playPause;
        } else {
          final leftControls = [
            ControlButton.playPause,
            ControlButton.rewind,
            ControlButton.forward
          ];
          final rightControls = [
            ControlButton.detection,
            ControlButton.subtitle,
            ControlButton.volume,
            ControlButton.speed,
            ControlButton.settings,
            ControlButton.fullscreen
          ];

          if (leftControls.contains(_focusedControl)) {
            final currentIndex = leftControls.indexOf(_focusedControl!);
            if (currentIndex < leftControls.length - 1) {
              _focusedControl = leftControls[currentIndex + 1];
            } else {
              _focusedControl = rightControls.first;
            }
          } else if (rightControls.contains(_focusedControl)) {
            final currentIndex = rightControls.indexOf(_focusedControl!);
            if (currentIndex < rightControls.length - 1) {
              _focusedControl = rightControls[currentIndex + 1];
            }
          }
        }
      });
    }
  }

  void _handleEnterKey() {
    if (_showVolumePopup) {
      _hideVolumePopup();
    } else if (_showSpeedPopup) {
      _hideSpeedPopup();
    } else if (_showSettingsPopup) {
      setState(() => _showSettingsPopup = false);
    } else if (_isTimelineMode) {
      setState(() {
        _isTimelineMode = false;
      });
    } else if (_focusedControl != null) {
      _executeControlAction(_focusedControl!);
    } else {
      _togglePlayPause();
    }
  }

  void _handleBackKey() {
    if (_showVolumePopup) {
      _hideVolumePopup();
    } else if (_showSpeedPopup) {
      _hideSpeedPopup();
    } else if (_showSettingsPopup) {
      setState(() => _showSettingsPopup = false);
    } else if (_isTimelineMode) {
      setState(() {
        _isTimelineMode = false;
      });
    } else if (_isFullscreen) {
      _toggleFullscreen();
    }
  }

  void _executeControlAction(ControlButton control) {
    switch (control) {
      case ControlButton.playPause:
        _togglePlayPause();
        break;
      case ControlButton.rewind:
        _seekBackward(seconds: 10);
        break;
      case ControlButton.forward:
        _seekForward(seconds: 10);
        break;
      case ControlButton.volume:
        _showVolumePopupDialog();
        break;
      case ControlButton.speed:
        _showSpeedPopupDialog();
        break;
      case ControlButton.settings:
        setState(() => _showSettingsPopup = !_showSettingsPopup);
        break;
      case ControlButton.fullscreen:
        _toggleFullscreen();
        break;
      case ControlButton.detection:
        _toggleDetection();
        break;
      case ControlButton.subtitle:
        _toggleSubtitle();
        break;
      default:
        break;
    }
  }

  void _toggleSubtitle() {
    if (_subtitleTracks.isEmpty) {
      _showSnackbar('No subtitles available');
      return;
    }

    if (_subtitleIndex == -1) {
      // Turn on first subtitle
      setState(() => _subtitleIndex = 0);
      _loadSubtitle(_subtitleTracks[0].url, _subtitleTracks[0].format);
    } else {
      // Turn off
      setState(() => _subtitleIndex = -1);
      _stopSubtitleSync();
      _subtitleController = null;
    }
  }

  void _showVolumePopupDialog() {
    setState(() {
      _showVolumePopup = true;
      _showSpeedPopup = false;
    });
    _volumePopupController.forward();
    _speedPopupController.reverse();
  }

  void _hideVolumePopup() {
    _volumePopupController.reverse().then((_) {
      if (mounted) {
        setState(() {
          _showVolumePopup = false;
        });
      }
    });
  }

  void _showSpeedPopupDialog() {
    setState(() {
      _showSpeedPopup = true;
      _showVolumePopup = false;
    });
    _speedPopupController.forward();
    _volumePopupController.reverse();
  }

  void _hideSpeedPopup() {
    _speedPopupController.reverse().then((_) {
      if (mounted) {
        setState(() {
          _showSpeedPopup = false;
        });
      }
    });
  }

  void _adjustVolume(double delta) {
    final newVolume = (_currentVolume + delta).clamp(0.0, 100.0);
    setState(() {
      _currentVolume = newVolume;
    });
    _videoPlayer.setVolume(newVolume);
    if (_mode != PlaybackMode.audioOnly) {
      _audioPlayer.setVolume(newVolume);
    }
  }

  void _adjustSpeed(double delta) {
    final newSpeed = (_currentSpeed + delta).clamp(0.25, 2.0);
    setState(() {
      _currentSpeed = newSpeed;
    });
    _videoPlayer.setRate(newSpeed);
    if (_mode == PlaybackMode.adaptive) _audioPlayer.setRate(newSpeed);
    if (_isDetectionEnabled) _detectionPlayer.setRate(newSpeed);
  }

  void _togglePlayPause() {
    if (_videoPlayer.state.playing) {
      _videoPlayer.pause();
      if (_mode == PlaybackMode.adaptive) _audioPlayer.pause();
      if (_isDetectionEnabled) _detectionPlayer.pause();
    } else {
      _videoPlayer.play();
      if (_mode == PlaybackMode.adaptive) _audioPlayer.play();
      if (_isDetectionEnabled) _detectionPlayer.play();
    }
  }

  void _seekForward({int seconds = 5}) {
    final currentPos = _timelinePlayer.state.position;
    final duration = _timelinePlayer.state.duration ?? Duration.zero;
    final newPos = (currentPos + Duration(seconds: seconds));
    if (newPos <= duration) {
      _videoPlayer.seek(newPos);
      if (_mode == PlaybackMode.adaptive) _audioPlayer.seek(newPos);
      if (_isDetectionEnabled) {
        final aheadPos = newPos + Duration(seconds: DETECTION_AHEAD_SECONDS);
        _detectionPlayer.seek(aheadPos);
        _detectionCache.clear();
      }
    }
  }

  void _seekBackward({int seconds = 5}) {
    final currentPos = _timelinePlayer.state.position;
    final newPos = currentPos - Duration(seconds: seconds);
    if (newPos >= Duration.zero) {
      _videoPlayer.seek(newPos);
      if (_mode == PlaybackMode.adaptive) _audioPlayer.seek(newPos);
      if (_isDetectionEnabled) {
        final aheadPos = newPos + Duration(seconds: DETECTION_AHEAD_SECONDS);
        _detectionPlayer.seek(aheadPos);
        _detectionCache.clear();
      }
    }
  }

