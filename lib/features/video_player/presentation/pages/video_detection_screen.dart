/// =====================
/// STRING EXTENSION FOR HTML PARSING
/// =====================

extension HtmlParser on String {
  String parseHtmlString() {
    String result = this;
    result = result.replaceAll(RegExp(r'<br\s*/?>'), '\n');
    result = result.replaceAll(RegExp(r'</p>\s*<p>'), '\n');
    result = result.replaceAll(RegExp(r'<[^>]*>'), '');
    result = result
        .replaceAll('&amp;', '&')
        .replaceAll('&lt;', '<')
        .replaceAll('&gt;', '>')
        .replaceAll('&quot;', '"')
        .replaceAll('&#39;', "'")
        .replaceAll('&apos;', "'")
        .replaceAll('&nbsp;', ' ')
        .replaceAll('&#160;', ' ');
    result = result
        .split('\n')
        .map((line) => line.trim())
        .where((line) => line.isNotEmpty)
        .join('\n');
    return result.trim();
  }
}

